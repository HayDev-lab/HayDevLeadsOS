export type DictKey = keyof (typeof DICT)["en"];

export function t(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  const table = DICT[locale] ?? DICT[DEFAULT_LOCALE];
  let s: string = (table as Record<string, string>)[key] ?? (DICT[DEFAULT_LOCALE] as Record<string, string>)[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.replace(`{${k}}`, String(vars[k]));
    }
  }
  return s;
}

export function resolveLocale(input?: string | null): Locale {
  if (input && (LOCALES_LIST as string[]).includes(input)) return input as Locale;
  return DEFAULT_LOCALE;
}

